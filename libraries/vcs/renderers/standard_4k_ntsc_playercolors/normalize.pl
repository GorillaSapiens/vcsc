sub slurp {
   my ($path) = @_;
   open(my $fh, '<:raw', $path) or die "could not open $path: $!\n";
   local $/;
   my $text = <$fh>;
   close($fh) or die "could not close $path: $!\n";
   $text = '' if !defined($text);
   $text =~ s/\r\n?/\n/g;
   return $text;
}

sub replace_once {
   my ($text_ref, $old, $new, $why) = @_;
   my $count = () = $$text_ref =~ /\Q$old\E/g;
   $count == 1 or die "normalizer expected exactly one $why, found $count\n";
   $$text_ref =~ s/\Q$old\E/$new/;
}

