my $new_proc = <<'ASM';
.proc vcs_standard_color_prepare_object_masks
.export vcs_standard_color_prepare_object_masks

     ; The retained five-strobe horizontal-position schedule still touches the
     ; absent missile slots. Keep both private coordinates bounded and stable.
     lda #0
     sta vcs_standard_color_object_x + 2
     sta vcs_standard_color_object_x + 3

; The sparse 44-byte layout preserves the visible loop's X=0,4,...,40 index
; and therefore its exact ball timing. Former missile slots now hold the two
; final-row colors; all other missile-mask bytes stay zero.

     ldy #0
     ldx #0
@clear:
     sty vcs_standard_color_object_masks,x
     sty vcs_standard_color_object_masks + 1,x
     sty vcs_standard_color_object_masks + 2,x
     txa
     clc
     adc #4
     tax
     cpx #44
     bcc @clear

     lda #87
     sta vcs_standard_color_object_masks + 31
     lda vcs_standard_color_ball_y
     ldy vcs_standard_color_ball_height
     ldx #0
     jsr @prepare_one

     lda vcs_standard_color_ball_y
     sta vcs_standard_color_object_masks + 7
     sec
     sbc #87
     sta vcs_standard_color_ball_y

     lda vcs_standard_color_player0_height
     clc
     adc #1
     sta vcs_standard_color_object_masks + 11
     lda vcs_standard_color_player1_height
     clc
     adc #1
     sta vcs_standard_color_object_masks + 15
     lda #0
     sta vcs_standard_color_object_masks + 19
     lda #1
     sta vcs_standard_color_object_masks + 23

     ; Precompute the five final-row values before visible drawing. Colors use
     ; the same storage-order index as their corresponding graphics row. When a
     ; player is absent, Y=0 reproduces the retained skip-path convention.
     lda vcs_standard_color_ball_height
     dec vcs_standard_color_ball_y
     cmp vcs_standard_color_ball_y
     rol
     rol
     sta vcs_standard_color_object_masks + 27

     lda vcs_standard_color_player1_y
     sec
     sbc #89
     tay
     cpy vcs_standard_color_object_masks + 15
     bcs @final_player1_zero
     lda (vcs_standard_color_player1_graphics),y
     sta vcs_standard_color_object_masks + 31
     lda.ay vcs_standard_color_player1_colors,y
     jmp @final_player1_color
@final_player1_zero:
     ldy #0
     lda #0
     sta vcs_standard_color_object_masks + 31
     lda.ay vcs_standard_color_player1_colors,y
@final_player1_color:
     sta vcs_standard_color_object_masks + 35

     lda vcs_standard_color_player0_y
     sec
     sbc #89
     tay
     cpy vcs_standard_color_object_masks + 11
     bcs @final_player0_zero
     lda (vcs_standard_color_player0_graphics),y
     sta vcs_standard_color_object_masks + 39
     lda.ay vcs_standard_color_player0_colors,y
     jmp @final_player0_color
@final_player0_zero:
     ldy #0
     lda #0
     sta vcs_standard_color_object_masks + 39
     lda.ay vcs_standard_color_player0_colors,y
@final_player0_color:
     sta vcs_standard_color_object_masks + 43
     rts

@prepare_one:
     sta vcs_standard_color_object_masks + 11
     stx vcs_standard_color_object_masks + 3
     sty vcs_standard_color_object_masks + 35
     sec
     sbc vcs_standard_color_object_masks + 35
     sta vcs_standard_color_object_masks + 7
     sta vcs_standard_color_object_masks + 39
     cmp vcs_standard_color_object_masks + 11
     bcc @no_wrap
     beq @no_wrap

     lda vcs_standard_color_object_masks + 11
     beq @wrapped_high
     cmp vcs_standard_color_object_masks + 31
     bcc @wrapped_low_ready
     beq @wrapped_low_ready
     lda vcs_standard_color_object_masks + 31
     sta vcs_standard_color_object_masks + 11
@wrapped_low_ready:
     lda #1
     sta vcs_standard_color_object_masks + 7
     jsr @set_range

@wrapped_high:
     lda vcs_standard_color_object_masks + 39
     cmp vcs_standard_color_object_masks + 31
     bcc @wrapped_high_ready
     beq @wrapped_high_ready
     rts
@wrapped_high_ready:
     sta vcs_standard_color_object_masks + 7
     lda vcs_standard_color_object_masks + 31
     sta vcs_standard_color_object_masks + 11
     jsr @set_range
     rts

@no_wrap:
     lda vcs_standard_color_object_masks + 7
     bne @no_wrap_first_ready
     lda #1
     sta vcs_standard_color_object_masks + 7
@no_wrap_first_ready:
     lda vcs_standard_color_object_masks + 11
     cmp vcs_standard_color_object_masks + 31
     bcc @no_wrap_last_ready
     beq @no_wrap_last_ready
     lda vcs_standard_color_object_masks + 31
     sta vcs_standard_color_object_masks + 11
@no_wrap_last_ready:
     lda vcs_standard_color_object_masks + 7
     cmp vcs_standard_color_object_masks + 11
     bcc @set_range
     beq @set_range
     rts

@set_range:
     lda vcs_standard_color_object_masks + 7
     sec
     sbc #1
     tay
     and #7
     tax
     lda @start_bits,x
     sta vcs_standard_color_object_masks + 23
     tya
     lsr
     lsr
     lsr
     sta vcs_standard_color_object_masks + 15

     lda vcs_standard_color_object_masks + 11
     sec
     sbc #1
     tay
     and #7
     tax
     lda @end_bits,x
     sta vcs_standard_color_object_masks + 27
     tya
     lsr
     lsr
     lsr
     sta vcs_standard_color_object_masks + 19

     lda vcs_standard_color_object_masks + 15
     asl
     asl
     clc
     adc vcs_standard_color_object_masks + 3
     tax
     lda vcs_standard_color_object_masks + 15
     cmp vcs_standard_color_object_masks + 19
     bne @range_many
     lda vcs_standard_color_object_masks + 23
     and vcs_standard_color_object_masks + 27
     ora vcs_standard_color_object_masks,x
     sta vcs_standard_color_object_masks,x
     rts

@range_many:
     lda vcs_standard_color_object_masks,x
     ora vcs_standard_color_object_masks + 23
     sta vcs_standard_color_object_masks,x
     inc vcs_standard_color_object_masks + 15
@range_middle:
     lda vcs_standard_color_object_masks + 15
     cmp vcs_standard_color_object_masks + 19
     bcs @range_last
     txa
     clc
     adc #4
     tax
