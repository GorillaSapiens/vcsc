# silently reintroduce layout-dependent cycle counts.
$renderer =~ s/^(\s*b(?:cc|cs|eq|mi|ne|pl|vc|vs))(\s+)/$1.same$2/mg;

sub emit_or_check {
   my ($name, $content) = @_;
   my $path = File::Spec->catfile($output_dir, $name);
   if ($check) {
      -f $path or die "$path is missing\n";
      my $actual = slurp($path);
      $actual eq $content or die "$path is stale; run $0\n";
      return;
   }
   open(my $fh, '>:raw', $path) or die "could not write $path: $!\n";
   print {$fh} $content;
   close($fh) or die "could not close $path: $!\n";
}

emit_or_check('standard_4k_ntsc_playercolors_renderer.s26', $renderer);
emit_or_check('standard_4k_ntsc_playercolors_macros.inc', $macros);
