sub eval_selected_expr {
   my ($expr, $path, $line_no) = @_;
   my $work = $expr;
   $work =~ s/\$([0-9A-Fa-f]+)/0x$1/g;
   $work =~ s/(?<![<>=!])=(?!=)/==/g;
   $work =~ s/&&/ and /g;
   $work =~ s/\|\|/ or /g;
   my %names = map { $_ => 1 } ($work =~ /\b([A-Za-z_][A-Za-z0-9_]*)\b/g);
   for my $name (keys %names) {
      next if $name eq 'and' || $name eq 'or';
      exists($defined{$name})
         or die "$path:$line_no: cannot normalize selected conditional with unknown symbol '$name': $expr\n";
      $work =~ s/\b\Q$name\E\b/$defined{$name}/g;
   }
   $work =~ /\A[\s0-9xa-fA-F()+\-*\/&|!<>=.andor]+\z/
      or die "$path:$line_no: unsupported selected conditional expression: $expr\n";
   my $value = eval $work; ## no critic (BuiltinFunctions::ProhibitStringyEval)
   die "$path:$line_no: could not evaluate selected conditional '$expr': $@\n" if $@;
   return $value ? 1 : 0;
}

sub selected_lines {
   my ($path, $content) = @_;
   my @out;
   my @stack;
   my $active = 1;
   my @lines = split(/\n/, $content, -1);
   for (my $i = 0; $i < @lines; ++$i) {
      my $line = $lines[$i];
      my $line_no = $i + 1;
      my $trim = $line;
      $trim =~ s/^\s+//;
      $trim =~ s/\s+$//;

      if ($trim =~ /^ifconst\s+([A-Za-z_.\$][A-Za-z0-9_.\$]*)\b/i) {
         my $cond = exists($defined{$1}) ? 1 : 0;
         push @stack, { parent => $active, cond => $cond, dynamic => 0, else => 0 };
         $active = $active && $cond;
         next;
      }
      if ($trim =~ /^ifnconst\s+([A-Za-z_.\$][A-Za-z0-9_.\$]*)\b/i) {
         my $cond = exists($defined{$1}) ? 0 : 1;
         push @stack, { parent => $active, cond => $cond, dynamic => 0, else => 0 };
         $active = $active && $cond;
         next;
      }
      if ($trim =~ /^if\s+(.+)$/i) {
         my $expr = $1;
         if ($expr =~ /\*/) {
            push @stack, { parent => $active, cond => 1, dynamic => 1, else => 0 };
            push @out, [ $line_no, $line ] if $active;
         } else {
            my $cond = $active ? eval_selected_expr($expr, $path, $line_no) : 0;
            push @stack, { parent => $active, cond => $cond, dynamic => 0, else => 0 };
            $active = $active && $cond;
         }
         next;
      }
      if ($trim =~ /^else\b/i) {
         @stack or die "$path:$line_no: ELSE without IF\n";
         my $frame = $stack[-1];
         $frame->{else} and die "$path:$line_no: duplicate ELSE\n";
         $frame->{else} = 1;
         if ($frame->{dynamic}) {
            push @out, [ $line_no, $line ] if $frame->{parent};
            $active = $frame->{parent};
         } else {
            $active = $frame->{parent} && !$frame->{cond};
         }
         next;
      }
      if ($trim =~ /^endif\b/i) {
         @stack or die "$path:$line_no: ENDIF without IF\n";
         my $frame = pop @stack;
         push @out, [ $line_no, $line ] if $frame->{dynamic} && $frame->{parent};
         $active = $frame->{parent};
         next;
      }

      push @out, [ $line_no, $line ] if $active;
   }
   @stack and die "$path: unterminated retained conditional\n";
   return \@out;
}

