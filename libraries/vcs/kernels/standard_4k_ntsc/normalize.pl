sub slurp {
   my ($path) = @_;
   open(my $fh, '<:raw', $path) or die "could not open $path: $!\n";
   local $/;
   my $text = <$fh>;
   close($fh) or die "could not close $path: $!\n";
   $text = '' if !defined($text);
   $text =~ s/\r\n?/\n/g;
   return $text;
}

my %text = map { $_ => slurp($input{$_}) } keys %input;

sub require_source {
   my ($which, $re, $why) = @_;
   $text{$which} =~ $re or die "$input{$which}: retained source no longer matches $why\n";
}

# Fail loudly if the selected retained-source relationships change.  This is a
# deliberately narrow normalizer, not a general DASM compatibility layer.
for my $name (qw(SLEEP VERTICAL_SYNC CLEAN_START SET_POINTER)) {
   require_source('macro', qr/^\s*MAC\s+\Q$name\E\b/im, "the $name macro");
}
require_source('header', qr/^\s*MAC\s+RETURN\b/im, 'the RETURN macro');
require_source('header', qr/^pfwidth\s*=\s*4\b/im, 'the default pfwidth=4 relationship');
require_source('header', qr/^pfadjust\s*=\s*0\b/im, 'the default pfadjust=0 relationship');
require_source('header', qr/^playfield\s*=\s*playfieldbase\b/im, 'the default playfield base relationship');
require_source('overscan', qr/^drawscreen\b/m, 'the drawscreen entry');
require_source('kernel', qr/^kernel\b/m, 'the non-reflected kernel entry');
require_source('kernel', qr/^\s*RETURN\s*$/m, 'the selected kernel return');
require_source('score', qr/^scoretable\b/m, 'the default score table');

sub source_rel {
   my ($path) = @_;
   my $rel = File::Spec->abs2rel($path, $vcs);
   $rel =~ s!\\!/!g;
   return $rel;
}

sub generated_header {
   my ($purpose) = @_;
   my @lines = (
      '; Generated by kernels/standard_4k_ntsc/normalize.pl.',
      '; Do not edit this file by hand; edit the normalizer or retained source.',
      ';',
      "; $purpose",
      '; Selected profile: NTSC, unbanked 4K, non-reflected standard kernel,',
      '; default asymmetric playfield, default decimal score, no optional hooks.',
      ';',
      '; Retained input SHA-256:',
   );
   for my $key (qw(macro header overscan kernel score)) {
      push @lines, sprintf(';   %s  %s', sha256_hex($text{$key}), source_rel($input{$key}));
   }
   push @lines, '';
   return join("\n", @lines);
}

sub macro_output {
   return generated_header('Deliberate vcsc-as ports of the five retained DASM macros.') . <<'ASM';
; SLEEP duration -- exact cycle delay, duration > 1.
; With --illegals, an odd delay begins with the exact three-cycle $04,$00
; zero-page NOP.  NO_ILLEGAL_OPCODES selects the retained BIT VSYNC fallback.
MACRO SLEEP duration
   .if duration < 2
      .error "MACRO ERROR: 'SLEEP': Duration must be > 1"
   .endif
   .if duration & 1
      .ifndef NO_ILLEGAL_OPCODES
         NOP.z $00
      .else
         BIT VSYNC
      .endif
      .repeat {duration - 3} / 2
         NOP
      .endrepeat
   .else
      .repeat duration / 2
         NOP
      .endrepeat
   .endif
ENDM

; VERTICAL_SYNC -- retained three-scanline vertical-sync sequence.
MACRO VERTICAL_SYNC
   LDA #$02
   STA WSYNC
   STA VSYNC
   STA WSYNC
   STA WSYNC
   LSR
   STA WSYNC
   STA VSYNC
ENDM

; CLEAN_START -- retained reset-time TIA/RAM/stack clearing sequence.
MACRO CLEAN_START
   SEI
   CLD
   LDX #0
   TXA
   TAY
@clear_stack:
   DEX
   TXS
   PHA
   BNE @clear_stack
ENDM

; SET_POINTER pointer,address -- load an absolute 16-bit address.
MACRO SET_POINTER pointer,address
   LDA #<{address}
   STA pointer
   LDA #>{address}
   STA pointer + 1
ENDM

; RETURN -- ordinary RTS in this deliberately unbanked profile.  The retained
; conditional remains explicit so accidentally defining bankswitch fails at
; assembly time rather than silently selecting an unsupported trampoline.
MACRO RETURN
   .ifdef bankswitch
      .error "standard_4k_ntsc RETURN does not support bankswitch"
   .else
      RTS
   .endif
ENDM
ASM
}

