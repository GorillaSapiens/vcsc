/* Stella SECAM exposes eight distinct colors.  The same eight colors repeat
 * across the TIA high nibble, so use the lowest canonical even byte for each
 * color. */
static const BuiltinRgbColor secam_palette[] = {
   {0x00,0x00,0x00,0x00},
   {0x02,0x21,0x21,0xff},
   {0x04,0xf0,0x3c,0x79},
   {0x06,0xff,0x50,0xff},
   {0x08,0x7f,0xff,0x00},
   {0x0a,0x7f,0xff,0xff},
   {0x0c,0xff,0xff,0x3f},
   {0x0e,0xff,0xff,0xff}
};

bool builtin_rgb_nearest(const BuiltinRgbColor *palette, size_t count,
                         long long r, long long g, long long b,
                         long long *value_out) {
   uint64_t best_distance = UINT64_MAX;
   uint8_t best_value = 0;

   if (!palette || count == 0 || !value_out) {
      return false;
   }

   for (size_t i = 0; i < count; i++) {
      int64_t dr = r - palette[i].r;
      int64_t dg = g - palette[i].g;
      int64_t db = b - palette[i].b;
      uint64_t distance = (uint64_t)(dr * dr + dg * dg + db * db);

      if (distance < best_distance ||
          (distance == best_distance && palette[i].value < best_value)) {
         best_distance = distance;
         best_value = palette[i].value;
      }
   }

   *value_out = best_value;
   return true;
}

bool builtin_ntsc_rgb_eval(long long r, long long g, long long b,
                           long long *value_out) {
   return builtin_rgb_nearest(ntsc_palette,
                              sizeof(ntsc_palette) / sizeof(ntsc_palette[0]),
                              r, g, b, value_out);
}

bool builtin_pal_rgb_eval(long long r, long long g, long long b,
                          long long *value_out) {
   return builtin_rgb_nearest(pal_palette,
                              sizeof(pal_palette) / sizeof(pal_palette[0]),
                              r, g, b, value_out);
}

bool builtin_secam_rgb_eval(long long r, long long g, long long b,
                            long long *value_out) {
   return builtin_rgb_nearest(secam_palette,
                              sizeof(secam_palette) / sizeof(secam_palette[0]),
                              r, g, b, value_out);
}
